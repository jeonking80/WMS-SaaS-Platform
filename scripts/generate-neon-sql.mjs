/** Generate a blank-demo-DB SQL Editor installer from the canonical migrations. */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export async function renderNeonInit({ through } = {}) {
  const directory = new URL('../db/migrations/', import.meta.url);
  const available = (await readdir(directory)).filter(name => name.endsWith('.sql')).sort();
  if (through !== undefined && (!Number.isInteger(through) || through < 1 || through > available.length)) throw new Error('Invalid migration prefix.');
  const names = available.slice(0, through ?? available.length);
  const destinations = names.includes('1792368000008_delivery-destinations.sql');
  const parts = [`-- Generated by node scripts/generate-neon-sql.mjs. Do not edit.
-- Run this entire file in Neon SQL Editor on an EMPTY wms_demo database.
-- No passwords are included. Both roles remain NOLOGIN until separately configured.
BEGIN;
DO $$
BEGIN
  IF current_database() <> 'wms_demo' THEN
    RAISE EXCEPTION 'Select the dedicated wms_demo database before running this file';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','f','S')) THEN
    RAISE EXCEPTION 'This installer requires an empty public schema; no existing data is changed';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('wms_migrator','wms_app')) THEN
    RAISE EXCEPTION 'WMS roles already exist; refusing to change existing identities';
  END IF;
END $$;
CREATE ROLE wms_migrator NOLOGIN;
CREATE ROLE wms_app NOLOGIN;
GRANT wms_migrator TO CURRENT_USER;
GRANT CONNECT, CREATE ON DATABASE wms_demo TO wms_migrator;
GRANT CONNECT ON DATABASE wms_demo TO wms_app;
ALTER SCHEMA public OWNER TO wms_migrator;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO wms_app;
SET LOCAL ROLE wms_migrator;
SET LOCAL search_path = public;
CREATE TABLE public.pgmigrations (
  id SERIAL PRIMARY KEY,
  name varchar(255) NOT NULL,
  run_on timestamp NOT NULL
);`];
  for (const name of names) {
    if (!/^\d+_[a-z0-9-]+\.sql$/.test(name)) throw new Error('Unexpected migration filename.');
    const contents = await readFile(new URL(name, directory), 'utf8');
    const up = contents.split('-- Down Migration')[0].replace('-- Up Migration', '').trim();
    if (!up || !contents.includes('-- Down Migration')) throw new Error('Unexpected migration format.');
    parts.push('-- ' + name + '\n' + up);
    parts.push("INSERT INTO public.pgmigrations(name, run_on) VALUES ('" + name.slice(0,-4) + "', CURRENT_TIMESTAMP);");
  }
  parts.push(`REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, wms_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON public."user", public.session, public.account,
  public.verification, public.items, public.warehouses, public.locations,
  public.inventory_documents, public.inventory_document_lines TO wms_app;
GRANT SELECT, INSERT, UPDATE ON public.stock_balances TO wms_app;
GRANT SELECT, INSERT ON public.stock_ledger, public.idempotency_requests, public.audit_logs TO wms_app;
GRANT SELECT ON public.tenants, public.memberships TO wms_app;
${destinations ? 'GRANT SELECT, INSERT, UPDATE ON public.delivery_destinations TO wms_app;' : ''}
RESET ROLE;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'wms_app'
    AND (rolsuper OR rolbypassrls OR rolcreaterole OR rolcreatedb OR rolcanlogin))
    OR pg_has_role('wms_app', 'wms_migrator', 'MEMBER') THEN
    RAISE EXCEPTION 'Unexpected application role privileges';
  END IF;
  IF (SELECT count(*) FROM public.pgmigrations) <> ${names.length}
    OR (SELECT count(*) FROM pg_tables WHERE schemaname='public') <> ${destinations ? 17 : 16}
    OR (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='public' AND c.relrowsecurity AND c.relforcerowsecurity) <> ${destinations ? 10 : 9}
    OR EXISTS (SELECT 1 FROM pg_tables WHERE schemaname='public' AND tableowner <> 'wms_migrator') THEN
    RAISE EXCEPTION 'Unexpected schema, migration or tenant isolation state';
  END IF;
END $$;
COMMIT;
SELECT current_database() AS database_name,
  (SELECT count(*) FROM public.pgmigrations) AS migrations_applied,
  (SELECT count(*) FROM pg_tables WHERE schemaname='public') AS tables_created,
  (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relrowsecurity AND c.relforcerowsecurity) AS forced_rls_tables;
`);
  return parts.join('\n\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../deploy/neon-init.sql', import.meta.url), await renderNeonInit());
  console.log('Generated deploy/neon-init.sql (no credentials).');
}
